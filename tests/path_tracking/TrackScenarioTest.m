    methods (Test)
        function testSkidpadCompleteRunGeometry(testCase)
            scenario = createPathTrackingSkidpadScenario(SampleDistance = 0.1);
            track = scenario.Track;
            trackData = makePathTrackingTrackData(track);
            pathS = (0:numel(track.X) - 1)' * track.SampleDistance;
            rightCurvature = track.Curvature( ...
                pathS > track.TimingLineS + 1.0 & ...
                pathS < track.RightLoopsEndS - 1.0);
            leftCurvature = track.Curvature( ...
                pathS > track.RightLoopsEndS + 1.0 & ...
                pathS < track.FinishLineS - 1.0);

            testCase.verifyFalse(track.IsClosed);
            testCase.verifyEqual(track.RunSequence, ...
                "Entry -> Right x2 -> Left x2 -> Exit");
            testCase.verifyEqual(track.RightCircleLapCount, 2);
            testCase.verifyEqual(track.LeftCircleLapCount, 2);
            testCase.verifyEqual([track.X(1), track.Y(1)], [0, -20], ...
                AbsTol = 1.0e-10);
            testCase.verifyEqual([track.X(end), track.Y(end)], [0, 20], ...
                AbsTol = 1.0e-10);
            testCase.verifyEqual(track.Length, ...
                40 + 8 * pi * track.CenterlineRadius, AbsTol = 2.0e-3);
            testCase.verifyEqual(min(track.X), -18.25, AbsTol = 2.0e-3);
            testCase.verifyEqual(max(track.X), 18.25, AbsTol = 2.0e-3);
            testCase.verifyEqual(track.PathWidth, 3.0, AbsTol = 1.0e-12);
            testCase.verifyEqual(double(trackData.SampleCount), ...
                numel(track.X));
            testCase.verifyLessThan(mean(rightCurvature), 0);
            testCase.verifyGreaterThan(mean(leftCurvature), 0);
        end

        function testAutocrossIsCounterclockwise(testCase)
            scenario = createPathTrackingAutocrossScenario();
            track = scenario.Track;
            signedArea = 0.5 * sum(track.X .* circshift(track.Y, -1) - ...
                circshift(track.X, -1) .* track.Y);

            testCase.verifyGreaterThan(signedArea, 0);
            testCase.verifyEqual(track.TraversalDirection, ...
                "counterclockwise");
            testCase.verifyEqual([track.X(1), track.Y(1)], [0, 0], ...
                AbsTol = 1.0e-12);
            testCase.verifyEqual(track.Length, 1000.0, ...
                AbsTol = 1.0e-10);
            testCase.verifyEqual(numel(track.X), 2000);
            testCase.verifyEqual(track.SourceDocument, ...
                "2024 FSEC竞赛手册Handbook");
            testCase.verifyEqual(track.SourceImageSHA256, ...
                "C769CEBF8EAE4CAA92D0BE26629C7665D393E9EADDB17C0314140CC57E7A0531");
            testCase.verifyTrue(isfile(track.SourceImage));
            testCase.verifyGreaterThanOrEqual( ...
                track.SourceTraceCoverage, 0.95);
            testCase.verifyTrue( ...
                track.ExtractionSettings.PruneSkeletonSpurs);
            testCase.verifyGreaterThan(size( ...
                track.ExtractionSettings.SupplementalPathWaypoints, 1), 2);
            testCase.verifySubstring(track.EventUsage, ...
                "not an official Autocross layout");

            closedStep = hypot(circshift(track.X, -1) - track.X, ...
                circshift(track.Y, -1) - track.Y);
            testCase.verifyEqual(mean(closedStep), ...
                track.SampleDistance, AbsTol = 2.0e-3);
            testCase.verifyLessThan(max(closedStep), ...
                1.2 * track.SampleDistance);
        end

        function testImageDerivedTrackUsesNamedDataFile(testCase)
            dataFolder = string(tempname);
            cleanup = onCleanup(@() removeFolderIfPresent(dataFolder));

            firstScenario = createPathTrackingAutocrossScenario( ...
                DataFolder = dataFolder);
            secondScenario = createPathTrackingAutocrossScenario( ...
                DataFolder = dataFolder);

            testCase.verifyFalse(firstScenario.Track.TrackData.Loaded);
            testCase.verifyTrue(secondScenario.Track.TrackData.Loaded);
            testCase.verifyTrue(isfile( ...
                secondScenario.Track.TrackData.File));
            testCase.verifyEqual(secondScenario.Track.TrackData.File, ...
                fullfile(dataFolder, "autocross.mat"));
            testCase.verifyEqual(secondScenario.Track.X, ...
                firstScenario.Track.X, AbsTol = 0.0);
            testCase.verifyEqual(secondScenario.Track.Y, ...
                firstScenario.Track.Y, AbsTol = 0.0);
            clear cleanup
        end

        function testGeneratedTracksUseNamedDataFiles(testCase)
            dataFolder = string(tempname);
            cleanup = onCleanup(@() removeFolderIfPresent(dataFolder));

            firstAcceleration = createPathTrackingAccelerationScenario( ...
                TargetSpeed = 10.0, DataFolder = dataFolder);
            secondAcceleration = createPathTrackingAccelerationScenario( ...
                TargetSpeed = 20.0, DataFolder = dataFolder);
            firstSkidpad = createPathTrackingSkidpadScenario( ...
                TargetSpeed = 6.0, DataFolder = dataFolder);
            secondSkidpad = createPathTrackingSkidpadScenario( ...
                TargetSpeed = 9.0, DataFolder = dataFolder);

            testCase.verifyFalse( ...
                firstAcceleration.Track.TrackData.Loaded);
            testCase.verifyTrue( ...
                secondAcceleration.Track.TrackData.Loaded);
            testCase.verifyEqual(secondAcceleration.Track.TrackData.File, ...
                fullfile(dataFolder, "acceleration.mat"));
            testCase.verifyEqual(secondAcceleration.Track.X, ...
                firstAcceleration.Track.X, AbsTol = 0.0);
            testCase.verifyEqual(secondAcceleration.Track.ReferenceSpeed, ...
                20.0 * ones(size(secondAcceleration.Track.X)), ...
                AbsTol = 0.0);

            testCase.verifyFalse(firstSkidpad.Track.TrackData.Loaded);
            testCase.verifyTrue(secondSkidpad.Track.TrackData.Loaded);
            testCase.verifyEqual(secondSkidpad.Track.TrackData.File, ...
                fullfile(dataFolder, "skidpad.mat"));
            testCase.verifyEqual(secondSkidpad.Track.X, ...
                firstSkidpad.Track.X, AbsTol = 0.0);
            testCase.verifyGreaterThan( ...
                max(secondSkidpad.Track.ReferenceSpeed), ...
                max(firstSkidpad.Track.ReferenceSpeed));
            testCase.verifyNotEqual( ...
                secondSkidpad.Track.TrackData.File, ...
                secondAcceleration.Track.TrackData.File);
            clear cleanup
        end

        function testClosedTrackPlotPathJoinsFinishToStart(testCase)
            scenario = createPathTrackingAutocrossScenario();
            track = scenario.Track;
            [plotX, plotY] = closeTrackPlotPath( ...
                track, double(track.X(:)), double(track.Y(:)));

            testCase.verifyGreaterThan(hypot( ...
                track.X(end) - track.X(1), ...
                track.Y(end) - track.Y(1)), 0.0);
            testCase.verifyNumElements(plotX, numel(track.X) + 1);
            testCase.verifyNumElements(plotY, numel(track.Y) + 1);
            testCase.verifyEqual([plotX(end), plotY(end)], ...
                [plotX(1), plotY(1)], AbsTol = 0.0);
            testCase.verifyEqual(plotX(1:end - 1), track.X, ...
                AbsTol = 0.0);
            testCase.verifyEqual(plotY(1:end - 1), track.Y, ...
                AbsTol = 0.0);
        end

