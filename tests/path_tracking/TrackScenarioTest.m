        function testAutocrossMarkedRegionsStartAndLateTurnAreRegularized( ...
                testCase)
            scenario = createPathTrackingAutocrossScenario();
            track = scenario.Track;
            s = (0:numel(track.X) - 1)' * track.SampleDistance;

            startMask = s <= 16.0 | s >= track.Length - 16.0;
            startPoints = [track.X(startMask), track.Y(startMask)];
            centeredPoints = startPoints - mean(startPoints, 1);
            [~, ~, directions] = svd(centeredPoints, 0);
            normalDirection = directions(:, 2);
            straightDeviation = abs(centeredPoints * normalDirection);

            lateTurnMask = s >= track.Length - 80.0 & ...
                s <= track.Length - 30.0;
            testCase.verifyLessThan(max(straightDeviation), 0.01);
            testCase.verifyLessThan(max(abs(track.X(startMask))), ...
                1.0e-10);
            testCase.verifyLessThan(track.Y(2), 0.0);
            testCase.verifyGreaterThan(track.Y(end), 0.0);
            testCase.verifyLessThan(max(abs( ...
                track.Curvature(startMask))), 0.01);
            testCase.verifyLessThan(max(abs( ...
                track.Curvature(lateTurnMask))), 0.22);
            testCase.verifyGreaterThan( ...
                track.GeometryRegularization.LateTurnPeakCurvatureBefore, ...
                0.50);
            testCase.verifyLessThan( ...
                track.GeometryRegularization.LateTurnPeakCurvatureAfter, ...
                0.22);
            regularization = track.GeometryRegularization;
            peakBefore = regularization.MarkedRegionPeakCurvatureBefore;
            peakAfter = regularization.MarkedRegionPeakCurvatureAfter;
            for regionIndex = 1:3
                testCase.verifyLessThan(peakAfter(regionIndex), ...
                    0.85 * peakBefore(regionIndex));
            end
            testCase.verifyEqual(regularization.StraightInnerDistance, ...
                16.0);
            testCase.verifyEqual(regularization.StraightOuterDistance, ...
                42.0);
            testCase.verifyEqual(regularization.StraightDirection, ...
                [0.0, -1.0]);
        end

        function testDirectionReversalSwapsTrackSides(testCase)
            track = makeClockwiseSquareTrack();
            orientedTrack = orientPathTrackingClosedTrack( ...
                track, "counterclockwise");

            testCase.verifyEqual(orientedTrack.LeftHalfWidth, ...
                [4; 7; 6; 5], AbsTol = 1.0e-12);
            testCase.verifyEqual(orientedTrack.RightHalfWidth, ...
                [1; 4; 3; 2], AbsTol = 1.0e-12);
            testCase.verifyTrue(orientedTrack.DirectionWasReversed);
            testCase.verifyGreaterThan(orientedTrack.SignedArea, 0);
        end

        function testOpenTrackCompletesAtPathEnd(testCase)
            scenario = createPathTrackingSkidpadScenario(SampleDistance = 0.5);
            sampleCount = numel(scenario.Track.X);
            [state, beforeFinish] = replayTrack( ...
                scenario, 1:sampleCount - 1, struct);
            [state, atFinish] = replayTrack( ...
                scenario, sampleCount, state);

            testCase.verifyFalse(beforeFinish);
            testCase.verifyTrue(atFinish);
            testCase.verifyEqual(state.EventDistance, ...
                scenario.Track.Length, AbsTol = scenario.Track.SampleDistance);
        end

        function testClosedTrackCompletesAfterRequestedLaps(testCase)
            scenario = createPathTrackingEnduranceScenario( ...
                NumberOfLaps = 2, SampleDistance = 0.5);
            sampleCount = numel(scenario.Track.X);
            [state, afterOneLap] = replayTrack( ...
                scenario, [1:sampleCount, 1], struct);
            [state, afterTwoLaps] = replayTrack( ...
                scenario, [2:sampleCount, 1], state);

            testCase.verifyFalse(afterOneLap);
            testCase.verifyTrue(afterTwoLaps);
            testCase.verifyEqual(state.EventDistance, ...
                2 * scenario.Track.Length, ...
                AbsTol = scenario.Track.SampleDistance);
        end

        function testStationaryAtFinishDoesNotComplete(testCase)
            scenario = createPathTrackingSkidpadScenario(SampleDistance = 0.5);
            sampleCount = numel(scenario.Track.X);
            [state, firstSample] = replayTrack( ...
                scenario, sampleCount, struct);
            [state, repeatedSample] = replayTrack( ...
                scenario, sampleCount, state);

            testCase.verifyFalse(firstSample);
            testCase.verifyFalse(repeatedSample);
            testCase.verifyEqual(state.EventDistance, 0, AbsTol = 1.0e-12);
        end

        function testOpenFinishGateCrossingCompletes(testCase)
            scenario = createPathTrackingSkidpadScenario(SampleDistance = 0.5);
            pathEnd = scenario.Track.Length;
            beforeFinish = struct( ...
                "Vehicle", struct("X", 0, "Y", 19.8), ...
                "Track", struct("PathS", pathEnd));
            afterFinish = struct( ...
                "Vehicle", struct("X", 0, "Y", 20.2), ...
                "Track", struct("PathS", pathEnd));

            [state, beforeCrossing] = updateLapCompletionState( ...
                struct, scenario, beforeFinish);
            [state, afterCrossing] = updateLapCompletionState( ...
                state, scenario, afterFinish);

            testCase.verifyFalse(beforeCrossing);
            testCase.verifyTrue(afterCrossing);
            testCase.verifyLessThan(state.EventDistance, ...
                scenario.Track.SampleDistance);
        end
    end
end

function [state, isComplete] = replayTrack(scenario, indices, state)
isComplete = false;
for index = reshape(indices, 1, [])
    snapshot = struct( ...
        "Vehicle", struct( ...
        "X", scenario.Track.X(index), ...
        "Y", scenario.Track.Y(index)));
    [state, isComplete] = updateLapCompletionState( ...
        state, scenario, snapshot);
end
end

function track = makeClockwiseSquareTrack()
track = struct( ...
    "IsClosed", true, ...
    "SampleDistance", 1.0, ...
    "X", [0; 0; 1; 1], ...
    "Y", [0; 1; 1; 0], ...
    "Heading", zeros(4, 1), ...
    "Curvature", zeros(4, 1), ...
    "ReferenceSpeed", [10; 20; 30; 40], ...
    "LeftHalfWidth", [1; 2; 3; 4], ...
    "RightHalfWidth", [4; 5; 6; 7]);
end

function removeFolderIfPresent(folderPath)
if isfolder(folderPath)
    rmdir(folderPath, "s");
end
end
