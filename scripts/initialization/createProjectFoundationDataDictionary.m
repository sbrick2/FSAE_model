function dictionaryPath = createProjectFoundationDataDictionary(projectRoot)
%CREATEProjectFoundationDATADICTIONARY Create or update ProjectFoundation data and bus definitions.
%   DICTIONARYPATH = CREATEProjectFoundationDATADICTIONARY(PROJECTROOT) creates the
%   VehicleData.sldd dictionary without inventing unknown vehicle values.

arguments
    projectRoot (1, 1) string = string(fileparts(fileparts(fileparts(mfilename("fullpath")))))
end

dataFolder = fullfile(projectRoot, "data");
if ~isfolder(dataFolder)
    mkdir(dataFolder);
end

dictionaryPath = fullfile(dataFolder, "VehicleData.sldd");
if isfile(dictionaryPath)
    dictionary = Simulink.data.dictionary.open(dictionaryPath);
else
    dictionary = Simulink.data.dictionary.create(dictionaryPath);
end

cleanup = onCleanup(@() close(dictionary));
designData = getSection(dictionary, "Design Data");

busDefinitions = createBusDefinitions();
busNames = fieldnames(busDefinitions);
for index = 1:numel(busNames)
    busName = busNames{index};
    setDictionaryEntry(designData, busName, busDefinitions.(busName));
end
saveChanges(dictionary);

for index = 1:numel(busNames)
    busName = busNames{index};
    defaultName = "Default" + string(busName);
    defaultValue = Simulink.Bus.createMATLABStruct(busName, [], 1, dictionary);
    defaultValue = applyDefaultOverrides(busName, defaultValue);
    setDictionaryEntry(designData, defaultName, defaultValue);
end

parameterGroups = createParameterGroups();
groupNames = fieldnames(parameterGroups);
for index = 1:numel(groupNames)
    groupName = groupNames{index};
    addDictionaryEntryIfMissing( ...
        designData, groupName, parameterGroups.(groupName));
end

saveChanges(dictionary);
fprintf("ProjectFoundation data dictionary updated: %s\n", dictionaryPath);
end

