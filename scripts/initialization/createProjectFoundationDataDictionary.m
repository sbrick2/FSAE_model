    LastUpdated = "2026-07-22", ...
    IsMeasured = logical(isMeasured), ...
    IsPlaceholder = logical(isPlaceholder), ...
    Notes = char(notes));
end

function setDictionaryEntry(section, name, value)
try
    entry = getEntry(section, name);
    setValue(entry, value);
catch exception
    if contains(exception.identifier, "EntryNotFound") || ...
            contains(exception.message, "does not exist", "IgnoreCase", true)
        addEntry(section, name, value);
    else
        rethrow(exception);
    end
end
end

function addDictionaryEntryIfMissing(section, name, value)
% Preserve audited physical data when setupProject refreshes bus schemas.
try
    getEntry(section, name);
catch exception
    if contains(exception.identifier, "EntryNotFound") || ...
            contains(exception.message, "does not exist", ...
            "IgnoreCase", true)
        addEntry(section, name, value);
    else
        rethrow(exception);
    end
end
end
