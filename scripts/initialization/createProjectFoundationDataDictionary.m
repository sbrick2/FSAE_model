function bus = makeBus(description, names, dimensions, dataTypes, units)
arguments
    description (1, 1) string
    names (1, :) string
    dimensions (1, :) cell
    dataTypes (1, :) string
    units (1, :) string
end

count = numel(names);
assert(numel(dimensions) == count && numel(dataTypes) == count && ...
    numel(units) == count, "Bus definition columns must have equal lengths.");

elements(1, count) = Simulink.BusElement;
for index = 1:count
    element = Simulink.BusElement;
    element.Name = char(names(index));
    element.Dimensions = dimensions{index};
    element.DataType = char(dataTypes(index));
    element.Unit = char(units(index));
    element.Description = char(description + ": " + names(index));
    elements(index) = element;
end

bus = Simulink.Bus;
bus.Description = char(description);
bus.Elements = elements;
end

function value = applyDefaultOverrides(busName, value)
switch string(busName)
    case "EnvironmentBus"
        value.RoadGripScale = ones(4, 1);
        value.RoadMuLimit = inf(4, 1);
        value.AirDensity = 0;
        value.AmbientTemperature = 0;
        value.Gravity = 9.80665;
    otherwise
        % Type-correct zeros and false values are created by Simulink.
end
end

