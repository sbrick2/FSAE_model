function catalog = listVehicleParameters(projectRoot, options)
%LISTVEHICLEPARAMETERS Read editable scalar vehicle parameters from the dictionary.
%   The catalog covers the physical vehicle and simulation groups stored in
%   VehicleData.sldd. Numeric vectors, maps, buses, and other compound data
%   remain outside this scalar editor.

arguments
    projectRoot (1, 1) string = defaultProjectRoot()
    options.DictionaryPath (1, 1) string = ""
end

dictionaryPath = options.DictionaryPath;
if strlength(dictionaryPath) == 0
    dictionaryPath = fullfile(projectRoot, "data", "VehicleData.sldd");
end
assert(isfile(dictionaryPath), "FSAE:VehicleParameters:MissingDictionary", ...
    "VehicleData.sldd was not found: %s", dictionaryPath);

dictionary = Simulink.data.dictionary.open(dictionaryPath);
cleanup = onCleanup(@() close(dictionary));
designData = getSection(dictionary, "Design Data");

groupNames = ["Vehicle", "Tire", "Aero", "Powertrain", ...
    "Battery", "Brake", "Simulation"];
groupLabels = ["整车", "轮胎", "空气动力", "动力总成", ...
    "电池", "制动", "仿真"];

groups = strings(0, 1);
labels = strings(0, 1);
names = strings(0, 1);
paths = strings(0, 1);
values = zeros(0, 1);
units = strings(0, 1);
lowerBounds = zeros(0, 1);
upperBounds = zeros(0, 1);
sources = strings(0, 1);
confidences = strings(0, 1);
placeholders = false(0, 1);
notes = strings(0, 1);

for groupIndex = 1:numel(groupNames)
    groupName = groupNames(groupIndex);
    groupValue = getValue(getEntry(designData, char(groupName)));
    if ~isstruct(groupValue) || ~isscalar(groupValue)
        continue
    end
    fieldNames = string(fieldnames(groupValue));
    for fieldIndex = 1:numel(fieldNames)
        fieldName = fieldNames(fieldIndex);
        record = groupValue.(char(fieldName));
        if ~isstruct(record) || ~isscalar(record) || ...
                ~isfield(record, "Value")
            continue
        end
        value = record.Value;
        if ~(isnumeric(value) && isreal(value) && isscalar(value))
            continue
        end

        groups(end + 1, 1) = groupName; %#ok<AGROW>
        labels(end + 1, 1) = groupLabels(groupIndex); %#ok<AGROW>
        names(end + 1, 1) = chineseParameterName( ...
            groupName, fieldName); %#ok<AGROW>
        paths(end + 1, 1) = groupName + "." + fieldName; %#ok<AGROW>
        values(end + 1, 1) = double(value); %#ok<AGROW>
        units(end + 1, 1) = stringMetadata(record, "Unit", "1"); %#ok<AGROW>
        lowerBounds(end + 1, 1) = numericMetadata( ...
            record, "LowerBound", NaN); %#ok<AGROW>
        upperBounds(end + 1, 1) = numericMetadata( ...
            record, "UpperBound", NaN); %#ok<AGROW>
        sources(end + 1, 1) = stringMetadata( ...
            record, "Source", ""); %#ok<AGROW>
        confidences(end + 1, 1) = stringMetadata( ...
            record, "Confidence", ""); %#ok<AGROW>
        placeholders(end + 1, 1) = logicalMetadata( ...
            record, "IsPlaceholder", false); %#ok<AGROW>
        notes(end + 1, 1) = stringMetadata(record, "Notes", ""); %#ok<AGROW>
    end
end

catalog = table(groups, labels, names, paths, values, units, ...
    lowerBounds, upperBounds, sources, confidences, placeholders, notes, ...
    'VariableNames', {'Group', 'GroupLabel', 'Name', 'Path', 'Value', ...
    'Unit', 'LowerBound', 'UpperBound', 'Source', 'Confidence', ...
    'IsPlaceholder', 'Notes'});
assert(~isempty(catalog), "FSAE:VehicleParameters:EmptyCatalog", ...
    "No editable scalar records were found in %s.", dictionaryPath);
end

