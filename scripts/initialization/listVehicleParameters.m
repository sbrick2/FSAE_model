function value = numericMetadata(record, fieldName, defaultValue)
value = defaultValue;
if isfield(record, fieldName)
    candidate = record.(fieldName);
    if isnumeric(candidate) && isreal(candidate) && isscalar(candidate)
        value = double(candidate);
    end
end
end

function value = stringMetadata(record, fieldName, defaultValue)
value = string(defaultValue);
if isfield(record, fieldName)
    candidate = string(record.(fieldName));
    if isscalar(candidate) && ~ismissing(candidate)
        value = candidate;
    end
end
end

function value = logicalMetadata(record, fieldName, defaultValue)
value = logical(defaultValue);
if isfield(record, fieldName)
    candidate = record.(fieldName);
    if (islogical(candidate) || isnumeric(candidate)) && isscalar(candidate)
        value = logical(candidate);
    end
end
end

function root = defaultProjectRoot()
root = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
end
