motorTorqueLimit = requiredNumericValue( ...
    parameters, "Powertrain", "MotorTorqueLimit");
motorResponseTime = requiredNumericValue( ...
    parameters, "Powertrain", "MotorResponseTime");
variables = struct( ...
    "UnifiedControlSampleTime", controlSampleTime, ...
    "UnifiedControlVehicleMass", requiredNumericValue( ...
        parameters, "Vehicle", "Mass"), ...
    "UnifiedControlGravity", 9.80665, ...
    "UnifiedControlWheelbase", requiredNumericValue( ...
        parameters, "Vehicle", "Wheelbase"), ...
    "UnifiedControlCGHeight", requiredNumericValue( ...
        parameters, "Vehicle", "CGHeight"), ...
    "UnifiedControlStaticLoadDistributionFront", requiredNumericValue( ...
        parameters, "Vehicle", "StaticLoadDistributionFront"), ...
    "UnifiedControlRollStiffnessDistributionFront", requiredNumericValue( ...
        parameters, "Vehicle", "RollStiffnessDistributionFront"), ...
    "UnifiedControlTrackFront", requiredNumericValue( ...
        parameters, "Vehicle", "TrackFront"), ...
    "UnifiedControlTrackRear", requiredNumericValue( ...
        parameters, "Vehicle", "TrackRear"), ...
    "UnifiedControlTireEffectiveRadius", requiredNumericValue( ...
        parameters, "Tire", "EffectiveRadius"), ...
    "UnifiedControlLowSpeedEpsilon", requiredNumericValue( ...
        parameters, "Tire", "LowSpeedEpsilon"), ...
    "UnifiedControlGearRatio", requiredNumericValue( ...
        parameters, "Powertrain", "GearRatio"), ...
    "UnifiedControlGearEfficiency", requiredNumericValue( ...
        parameters, "Powertrain", "GearEfficiency"), ...
    "UnifiedControlMotorTorqueLimit", motorTorqueLimit, ...
    "UnifiedControlMotorSpeedLimit", requiredNumericValue( ...
        parameters, "Powertrain", "MotorSpeedLimit"), ...
    "UnifiedControlInverterEfficiency", requiredNumericValue( ...
        parameters, "Powertrain", "InverterEfficiency"), ...
    "UnifiedControlDrivePowerLimit", requiredNumericValue( ...
        parameters, "Battery", "PowerLimitDrive"), ...
    "UnifiedControlRegenPowerLimit", requiredNumericValue( ...
        parameters, "Battery", "PowerLimitRegen"), ...
    "UnifiedControlBrakeMaxTorque", requiredNumericVector4( ...
        parameters, "Brake", "MaxTorquePerWheel"), ...
    "UnifiedControlBatterySOCUpperLimit", requiredNumericValue( ...
        parameters, "Battery", "SOCUpperLimit"), ...
    "UnifiedControlPowerEpsilon", requiredNumericValue( ...
        parameters, "Battery", "PowerEpsilon"), ...
    "UnifiedControlMotorTorqueRateLimit", motorTorqueLimit / ...
        max(motorResponseTime, controlSampleTime), ...
    "UnifiedControlFrictionEstimate", 1.0, ...
    "UnifiedControlTCSlipOn", 0.12, ...
    "UnifiedControlTCSlipOff", 0.08, ...
    "UnifiedControlTCSlipFullCut", 0.25, ...
    "UnifiedControlMinimumNormalLoad", 50.0, ...
    "UnifiedControlEnergyDriveFraction", 0.90, ...
    "UnifiedControlForcePriorityWeight", 1.0, ...
    "UnifiedControlYawPriorityWeight", 4.0, ...
    "UnifiedControlRegularizationWeight", 1.0e-4, ...
    "UnifiedControlAllocatorIterations", uint8(24), ...
    "UnifiedControlMaximumAcceleration", driver.MaximumAcceleration, ...
    "UnifiedControlMaximumDeceleration", driver.MaximumDeceleration, ...
    "TorqueVectoringControlSampleTime", controlSampleTime);
variableNames = string(fieldnames(variables));
for variableName = variableNames.'
    in = in.setVariable(variableName, variables.(variableName));
end
end

function value = requiredNumericValue(parameters, groupName, fieldName)
assert(isfield(parameters, groupName) && ...
    isfield(parameters.(groupName), fieldName), ...
    "FSAE:AAD:MissingParameter", ...
    "Missing adaptive-driver parameter %s.%s.", groupName, fieldName);
value = parameters.(groupName).(fieldName);
if isa(value, "Simulink.Parameter")
    value = value.Value;
elseif isstruct(value) && isfield(value, "Value")
    value = value.Value;
end
assert(isnumeric(value) && isscalar(value) && isfinite(value), ...
    "FSAE:AAD:InvalidParameter", ...
    "Adaptive-driver parameter %s.%s must be finite and scalar.", ...
    groupName, fieldName);
value = double(value);
end

function value = requiredNumericVector4(parameters, groupName, fieldName)
assert(isfield(parameters, groupName) && ...
    isfield(parameters.(groupName), fieldName), ...
    "FSAE:AAD:MissingParameter", ...
    "Missing adaptive-controller parameter %s.%s.", ...
    groupName, fieldName);
value = parameters.(groupName).(fieldName);
if isa(value, "Simulink.Parameter")
    value = value.Value;
elseif isstruct(value) && isfield(value, "Value")
    value = value.Value;
end
assert(isnumeric(value) && numel(value) == 4 && ...
    all(isfinite(value(:))), ...
    "FSAE:AAD:InvalidParameter", ...
    "Adaptive-controller parameter %s.%s must have four finite values.", ...
    groupName, fieldName);
value = reshape(double(value), 4, 1);
end

function modelMode = mapTireModel(tireModel)
tireModel = lower(string(tireModel));
validModels = ["simple", "mf62", "ttc_map"];
index = find(tireModel == validModels, 1);
if isempty(index)
    error("FSAE:Lap:InvalidTireModel", ...
        "Vehicle.TireModel 收到 '%s'，允许值为：simple、mf62、ttc_map。", ...
        tireModel);
end
modelMode = index - 1;
end
